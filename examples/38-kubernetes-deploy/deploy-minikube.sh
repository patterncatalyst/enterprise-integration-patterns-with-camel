#!/usr/bin/env bash
#
# deploy-minikube.sh — build one runtime variant of the Appendix T example,
# load the image into the minikube profile, deploy it, and send one order
# through the published NodePort.
#
#   ./examples/38-kubernetes-deploy/deploy-minikube.sh quarkus
#   ./examples/38-kubernetes-deploy/deploy-minikube.sh spring-boot
#
# Needs ./scripts/setup-minikube-stack.sh first. Both variants deploy as
# Deployment/Service eip-k8s-deploy on NodePort 30088, so the second one
# replaces the first.
#
# Images: docker build, then `minikube image load` into the profile's
# containerd. No registry, no `minikube docker-env` (the node runs
# containerd, not Docker), imagePullPolicy Never.
set -euo pipefail

RUNTIME="${1:-quarkus}"
PROFILE="${MINIKUBE_PROFILE:-eip}"
CTX="$PROFILE"
TAG=1.0
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
URL="http://127.0.0.1:30088"

fail() { echo "ERROR: $*" >&2; exit 1; }
k() { kubectl --context "$CTX" "$@"; }

case "$RUNTIME" in
  quarkus)     IMAGE="eip/eip-k8s-deploy:$TAG";             HEALTH=/q/health/ready ;;
  spring-boot) IMAGE="eip/eip-k8s-deploy-springboot:$TAG";  HEALTH=/actuator/health/readiness ;;
  *) fail "runtime must be quarkus or spring-boot" ;;
esac
DIR="$HERE/$RUNTIME"

minikube status -p "$PROFILE" >/dev/null 2>&1 || fail "minikube profile $PROFILE is not running: ./scripts/setup-minikube-stack.sh"
k get kafka eip-kafka -n kafka >/dev/null 2>&1 || fail "Kafka missing: ./scripts/setup-minikube-stack.sh"

echo "==> mvn package ($RUNTIME)"
mvn -B -q -f "$DIR/pom.xml" package -DskipTests

echo "==> docker build $IMAGE"
docker build -q -f "$DIR/Containerfile" -t "$IMAGE" "$DIR" >/dev/null

echo "==> minikube -p $PROFILE image load $IMAGE"
minikube -p "$PROFILE" image load --overwrite=true "$IMAGE"

echo "==> Deploying"
# The two variants select their pods with different labels, and a
# Deployment selector is immutable: replace the Deployment rather than
# patching the other variant's. This also picks up a reloaded image.
k delete deployment/eip-k8s-deploy --ignore-not-found --wait=true >/dev/null
if [[ "$RUNTIME" == quarkus ]]; then
  # Generated by quarkus-kubernetes from application.properties.
  k apply -f "$DIR/target/kubernetes/kubernetes.yml" >/dev/null
else
  k apply -f "$DIR/k8s/" >/dev/null
fi
k rollout status deployment/eip-k8s-deploy --timeout=300s >/dev/null || fail "rollout failed: kubectl --context $CTX get pods"

echo "==> Checks through the published NodePort ($URL)"
for _ in $(seq 1 30); do
  curl -sf -o /dev/null "$URL$HEALTH" && break
  sleep 2
done
code=$(curl -s -o /dev/null -w '%{http_code}' "$URL$HEALTH")
[[ "$code" == 200 ]] || fail "$HEALTH returned $code"
echo "    $HEALTH -> 200"

ORDER_ID="ORD-K8S-$(date +%s)"
reply=$(curl -sf -X POST "$URL/api/orders" -H 'Content-Type: application/json' \
  -d "{\"orderId\":\"$ORDER_ID\",\"customerId\":\"C-101\",\"item\":\"Shipping Container\",\"quantity\":2}")
echo "    POST /api/orders -> $reply"

for _ in $(seq 1 30); do
  if k logs deployment/eip-k8s-deploy --since=5m 2>/dev/null | grep "Enriched order published" | grep "$ORDER_ID" | grep -q "Global Freight Ltd"; then
    echo "    $ORDER_ID enriched with customerName Global Freight Ltd (from Redis) and published"
    echo "==> $RUNTIME variant deployed and verified on $PROFILE"
    exit 0
  fi
  sleep 2
done
fail "no enriched order for $ORDER_ID in the logs: kubectl --context $CTX logs deployment/eip-k8s-deploy"
